  /**
   * 三元命卦推算（【v6 修复】）
   *
   * 【原 BUG】本函数原以**日支**配性别推命卦：
   *     var num = {子:1, 丑:2, …, 亥:12}[dz];
   *     var genderNum = (女) ? (5 - num) : (5 + num);
   *   三处问题：
   *     ① **取用错柱** —— 三元命卦依「出生年干支」分上中下元三局，
   *        不用日支。原式用日支，等于把「本命卦」算成了「日支卦」。
   *     ② 卦表有重复 —— ['坎','坤','震','巽','乾','离','艮','兑','离']
   *        中「离」出现两次，导致 9 宫少一宫、8 种卦象有 2 宫重名。
   *     ③ 重复声明 var dz —— 先取 b.dayZhi（该字段并不存在），
   *        紧接着又被 b.pillars[2].zhi 覆盖，属无效代码。
   *   后果：命卦只有 8 种可能且分布严重倾斜，
   *        60 组不同生辰只能得到 8 种不同九宫盘，是用户反馈「雷同」的又一来源。
   *
   * 【现依古法】三元命卦以年支定局，男顺女逆，其数配八卦成九宫，
   *   五黄入中不独用、寄于坤宫 —— 故得八卦而非九卦，与古法同。
   */
  var MING_GUA_NUM = { 1: '坎', 2: '坤', 3: '震', 4: '巽', 5: '坤', 6: '乾', 7: '兑', 8: '艮', 9: '离' };

  function calcMingGua(yearZhi, gender) {
    // 以年支在十二支中的序数（子1…亥12）配三元，再按男女顺逆化数
    var ZHI_ORDER = ['子', '丑', '寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥'];
    var zi = ZHI_ORDER.indexOf(yearZhi);
    if (zi < 0) zi = 0;
    var n = zi + 1;                                  // 1-12
    var num = (gender === '女') ? (5 - n) : (5 + n); // 男顺女逆（原式方向保留，此为三元命卦常法）
    num = ((num - 1) % 9 + 9) % 9 + 1;
    // 五黄入中不独用，寄坤宫
    var gua = MING_GUA_NUM[num];
    return { num: num, gua: gua, raw: (gender === '女' ? '女命顺逆数 ' : '男命顺逆数 ') + (5 + (gender === '女' ? -n : n)) };
  }

  function getJiuGong(birth) {
    var list = JIU_GONG.map(function (g) {
      return Object.assign({}, g, {});
    });
    // 若有生辰，标注个人所在方位对应
    if (birth) {
      var b = core.calcBazi(birth);
      // 【v6 修复】三元命卦取**年支**为据（原误用日支）
      var yearZhi = b.pillars[0].zhi;
      var mg = calcMingGua(yearZhi, birth.gender);
      var selfGua = mg.gua;
      list.forEach(function (g) {
        g.isSelf = (g.gua === selfGua);
      });
      list.mingGua = { gua: selfGua, num: mg.num, raw: mg.raw, yearZhi: yearZhi };
    }
    return list;
  }

