  /**
   * 装卦：三钱六爻，每爻真实掷三枚独立铜钱，共 18 个面
   *
   * 【1.5.0 修复】原实现是 `Math.floor(Math.random()*100)` 后按 12.5/50/62.5 分档，
   * 得到 12.5% / 37.5% / 12.5% / 37.5% —— 少阴 8 与老阳 9 的概率被互换了。
   * 标准三钱法为 1:3:3:1（12.5% / 37.5% / 37.5% / 12.5%）：
   *   三背=9 老阳 1/8，两背一反=7 少阳 3/8，一背两反=8 少阴 3/8，三反=6 老阴 1/8。
   * 现在改为真实掷钱：每枚钱独立等概率，爻值由三枚钱面求和得出。
   * 依据：《周易·系辞》，三钱六爻通行法。
   */
  function castHexagram(opt) {
    opt = opt || {};
    var core = opt.core || (typeof JiuGongCoin !== 'undefined' ? JiuGongCoin : null);
    if (core) {
      var r = core.cast({ rng: opt.rng, crypto: opt.crypto });
      return opt.detail ? r.lines : r.lines.map(function (l) { return l.value; });
    }
    // 兜底：环境未加载 core/coin.js 时，仍保证 1:3:3:1 的正确分布
    var lines = [];
    for (var i = 0; i < 6; i++) {
      var sum = 0;
      for (var k = 0; k < 3; k++) sum += Math.random() < 0.5 ? 3 : 2; // 3=背(阳) 2=字(阴)
      lines.push(sum); // 6 / 7 / 8 / 9
    }
    return lines;
  }

  // 爻 → 阴阳 / 是否动
  function lineYang(v) { return v === 7 || v === 9; }
  function lineChanging(v) { return v === 6 || v === 9; }

  /**
   * 爻值合法性验证
   * 【1.5.0 修复】原实现只认 6/9 为动爻，但 divinationByTime 传入的是 0/5，
   * 导致时间起卦的动爻被完全忽略（动爻数恒为 0、无变卦）。
   * 现统一：只接受 6/7/8/9，0/5 等非法值一律拒绝。
   */
  function assertValidLines(lines) {
    if (!lines || lines.length !== 6) {
      throw new Error('爻数组长度必须为 6，实际 ' + (lines ? lines.length : 'null'));
    }
    for (var i = 0; i < 6; i++) {
      var v = lines[i];
      if (v !== 6 && v !== 7 && v !== 8 && v !== 9) {
        throw new Error('第' + (i + 1) + '爻值 ' + v + ' 非法，只允许 6/7/8/9');
      }
    }
    return true;
  }

  /**
   * 由爻值数组推本卦与变卦（简化采用二进制对应法）
   * 下卦 = 第1~3爻，上卦 = 第4~6爻
   */
  function hexagramFromLines(lines) {
    var names = ['乾', '坤', '震', '巽', '坎', '离', '艮', '兑'];
    function trigram(a, b, c) {
      var bits = (lineYang(a) ? 1 : 0) * 4 + (lineYang(b) ? 1 : 0) * 2 + (lineYang(c) ? 1 : 0);
      return names[bits];
    }
    var lower = trigram(lines[0], lines[1], lines[2]);
    var upper = trigram(lines[3], lines[4], lines[5]);
    // 上卦在前，如「乾上坤下」= 泰
    return upper + lower;
  }

  // 上下卦 -> 64卦名查找
  function guaNameFrom(upper, lower) {
    for (var row of GUA64) { if (row[2] === upper && row[3] === lower) return row[0]; }
    for (var i = 0; i < GUA64.length; i++) {
      var nm = GUA64[i][0];
      // 拆解：如「水雷屯」= 上坎下震
      var map = { '乾': '乾', '坤': '坤', '震': '震', '巽': '巽', '坎': '水', '离': '火', '艮': '山', '兑': '泽' };
      if (nm.length === 3) {
        var up = nm.charAt(0), low = nm.charAt(1);
        // 转回八卦名
        var back = { '水': '坎', '火': '离', '山': '艮', '泽': '兑', '雷': '震', '风': '巽', '天': '乾', '地': '坤' };
        var upG = back[up], lowG = back[low];
        if (upG === upper && lowG === lower) return nm;
      } else if (nm.length === 4) {
        // 如「泽水困」「水泽节」，逐字
        var back2 = { '水': '坎', '火': '离', '山': '艮', '泽': '兑', '雷': '震', '风': '巽', '天': '乾', '地': '坤' };
        var u = back2[nm.charAt(0)], l = back2[nm.charAt(1)];
        if (u === upper && l === lower) return nm;
      } else if (nm.length === 2) {
        if (nm === upper + lower || nm === lower + upper) return nm;
      }
    }
    // 兜底：按宫位找
    return upper + lower;
  }

