  /**
   * 三星连珠 —— 数字起卦
   * 选三个 1-99 的数字（可报手机尾号、房间号、时间等），系统按规则成卦。
   * 规则：三个数字之和除 8 取余为上卦（余 0 作 8），除 6 取余为下卦（余 0 作 6），
   *       总和除 6 定动爻（余 0 作 6）。不掷骰，完全由数字决定，便于复现。
   */
  function divinationByNumbers(n1, n2, n3, opt) {
    opt = opt || {};
    var a = Math.abs(parseInt(n1, 10)), b = Math.abs(parseInt(n2, 10)), c = Math.abs(parseInt(n3, 10));
    if (!isFinite(a) || !isFinite(b) || !isFinite(c) || a < 1 || b < 1 || c < 1) {
      throw new Error('请填写三个大于 0 的数字');
    }
    if (a > 999 || b > 999 || c > 999) {
      throw new Error('数字请不要超过 999');
    }

    // 梅花易数《梅花年月日时发看法》：
    //   下卦 = (第一数 + 第二数) ÷ 8 取余（余 0 作 8），配先天八卦数定下卦
    //   上卦 = (第一数 + 第三数) ÷ 8 取余（余 0 作 8）
    //   动爻 = (三数之和) ÷ 6 取余（余 0 作 6）
    // 梅花易数先天数：乾1 兑2 离3 震4 巽5 坎6 艮7 坤8
    var XIAN_TIAN = ['', '乾', '兑', '离', '震', '巽', '坎', '艮', '坤'];
    var lowIdx = (a + b) % 8 || 8;
    var upIdx = (a + c) % 8 || 8;
    var moveIdx = (a + b + c) % 6 || 6;
    var low = XIAN_TIAN[lowIdx];
    var up = XIAN_TIAN[upIdx];

    // 找卦名
    var name = '';
    for (var i = 0; i < GUA64.length; i++) {
      if (GUA64[i][2] === up && GUA64[i][3] === low) { name = GUA64[i][0]; break; }
    }
    if (!name) name = up + '上' + low + '下';

    // 先按上下卦定六爻（此时尚未动爻，卦象纯净）
    var lines = [7, 7, 7, 7, 7, 7];
    for (var k = 0; k < 6; k++) {
      lines[k] = isYangByTrigram(up, low, k) ? 7 : 8;
    }
    // 置动爻：阳爻动置老阳(9，阴变)，阴爻动置老阴(6，阳变)
    var castLines = lines.slice();
    castLines[moveIdx - 1] = (castLines[moveIdx - 1] === 7) ? 9 : 6;

    // 传 guaName 固定本卦名（因动爻会改变上/下卦的爻象组合，
    // 若由 buildGuaName 重算会得到错误卦名）；变卦由 castLines 自然翻转得出
    var d = divination({
      question: opt.question || '数字起卦',
      category: opt.category || '综合',
      lines: castLines,
      guaName: name
    });
    d.method = '三星连珠 · 数字起卦';
    d.numbers = [a, b, c];
    d.sum = a + b + c;
    d.formula = a + '+' + b + '=' + (a + b) + '÷8 余 ' + lowIdx + '（下卦' + low + '）；'
      + a + '+' + c + '=' + (a + c) + '÷8 余 ' + upIdx + '（上卦' + up + '）；'
      + (a + b + c) + '÷6 余 ' + moveIdx + '（第' + moveIdx + '爻动）';
    return d;
  }

  /** 依上下卦取某爻阴阳。idx: 0=初爻 1=二爻 2=三爻 3=四爻 4=五爻 5=上爻 */
  var TRI_YANG = {
    '乾': '111', '兑': '110', '离': '101', '震': '100',
    '巽': '011', '坎': '010', '艮': '001', '坤': '000'
  };
  function isYangByTrigram(up, low, idx) {
    var t = idx < 3 ? low : up;
    var pos = idx < 3 ? idx : idx - 3;      // 卦内位序：0=下 1=中 2=上
    return TRI_YANG[t].charAt(pos) === '1';
  }

  /**
   * 此刻起卦 —— 时间起卦
   * 以当下年支数 + 月 + 日成卦（《梅花易数》法），随时随地可起一卦。
   */
  function divinationByTime(a, b) {
    /* 【v6 修复 BUG】原实现签名是 divinationByTime(opt)，
     * 但函数体第一行就 `var now = new Date()`，完全无视传入的 opt.date；
     * 且卦象用儒略日算、六爻全为静爻（无动爻），
     * 于是无论传什么日期，120 组输入只得到 1 种输出（100% 坍缩）。
     * 同时 opt.category 也被丢弃，断语永远按「综合」出。
     * 现改为：支持 (date, opt) 与 ({date, category}) 两种调用方式。
     *
     * 依据：《梅花易数》「以年月日时起卦」——
     *   上卦 =（年支序 + 月 + 日）÷ 8 取余，余 0 作 8
     *   下卦 =（年支序 + 月 + 日 + 时支序）÷ 8 取余
     *   动爻 =（年支序 + 月 + 日 + 时支序）÷ 6 取余，余 0 作 6
     * 动爻作老阴（阳变阴）或老阳（阴变阳），从而得变卦与动爻应期。
     */
    var opt = {}, now;
    if (a instanceof Date) { now = a; opt = b || {}; }
    else { opt = a || {}; now = (opt.date instanceof Date) ? opt.date : new Date(); }

    var l = Lunar.fromDate(now);
    /* 年支序：子 1 … 亥 12 */
    var ZHI_SEQ = { 子: 1, 丑: 2, 寅: 3, 卯: 4, 辰: 5, 巳: 6, 午: 7, 未: 8, 申: 9, 酉: 10, 戌: 11, 亥: 12 };
    var yearZhi = l.getYearZhi ? l.getYearZhi() : '子';
    var ySeq = ZHI_SEQ[yearZhi] || 1;
    var lMonth = l.getMonth ? Math.abs(l.getMonth()) : (now.getMonth() + 1);
    var lDay = l.getDay ? l.getDay() : now.getDate();
    /* 时支序：23:00 起为子时（依《梅花易数》夜子时算法） */
    var hourZhiIdx = Math.floor(((now.getHours() + 1) % 24) / 2);
    var hSeq = hourZhiIdx + 1;

    var XIAN_TIAN = ['', '乾', '兑', '离', '震', '巽', '坎', '艮', '坤'];
    var sumUp = ySeq + lMonth + lDay;
    var sumLow = sumUp + hSeq;
    var upNum = sumUp % 8 || 8;
    var lowNum = sumLow % 8 || 8;
    var up = XIAN_TIAN[upNum];
    var low = XIAN_TIAN[lowNum];
    var dongSum = sumLow;
    var dongYao = dongSum % 6 || 6;

    var name = '';
    for (var i = 0; i < GUA64.length; i++) {
      if (GUA64[i][2] === up && GUA64[i][3] === low) { name = GUA64[i][0]; break; }
    }
    if (!name) name = up + low;

    /* 装卦：静爻依 isYangByTrigram 定阴阳。
     * 【1.5.0 修复】原实现在动爻位传 0（阳动）或 5（阴动），
     * 而 lineChanging() 只认 6/9，因此动爻被完全丢弃：
     * 时间起卦无论传入什么日期，动爻数恒为 0、变卦恒为空。
     * 现改为三钱法爻值：阳爻动用老阳 9（阳变阴），阴爻动用老阴 6（阴变阳）。 */
    var lines = [];
    for (var k = 0; k < 6; k++) {
      var yang = isYangByTrigram(up, low, k);
      if (k === dongYao - 1) lines.push(yang ? 9 : 6);
      else lines.push(yang ? 7 : 8);
    }
    assertValidLines(lines);
    var d = divination({
      question: opt.question || '此刻起卦',
      category: opt.category || '综合',
      lines: lines,
      guaName: name
    });
    d.method = '时间起卦（梅花易数「年月日时」法）';
    d.formula = '农历' + lMonth + '月' + lDay + '日·' + hourZhiIdx + '时辰，年支' + yearZhi + '（' + ySeq + '）'
      + '　上卦＝(' + ySeq + '+' + lMonth + '+' + lDay + ')÷8余' + upNum + '＝' + up
      + '　下卦＝上式+' + hSeq + '÷8余' + lowNum + '＝' + low
      + '　动爻＝(' + ySeq + '+' + lMonth + '+' + lDay + '+' + hSeq + ')÷6余' + dongYao;
    d.timeGua = { up: up, low: low, dongYao: dongYao, lunarMonth: lMonth,
      lunarDay: lDay, yearZhi: yearZhi, hourZhi: hourZhiIdx };
    return d;
  }

