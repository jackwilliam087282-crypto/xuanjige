  function buildTiming(main, changed, lines) {
    var moveIdx = [];
    (lines || []).forEach(function (v, i) { if (lineChanging(v)) moveIdx.push(i); });
    var scope = moveIdx.length ? moveIdx : [5];   // 无动爻则以上爻（事之终）为应期

    // 以动爻中位者定主应期
    var mid = scope[Math.floor(scope.length / 2)];
    var q = YING_QI[mid];
    var parts = [];
    parts.push('主应期在' + q.unit + '之' + midName(mid) + '：' + q.hint + '。');

    if (moveIdx.length > 1) {
      parts.push('本卦有' + moveIdx.length + '爻动（' +
        moveIdx.map(function (i) { return midName(i) + '爻'; }).join('、') +
        '），主应期取其中位' + midName(mid) + '爻，余爻为旁应，可作旁证。');
    } else if (moveIdx.length === 1) {
      parts.push('唯' + midName(mid) + '爻独动，事机专一，应期较实。');
    } else {
      parts.push('六爻安静，无变动之象，应期难定，须以所问之事的自然周期为断。');
    }

    if (changed) {
      // 变卦动爻与本卦动爻同位，取其对应爻位之应期作转折期
      var t = YING_QI[mid];
      parts.push('变卦【' + changed.fullName + '】主事后之变，转折点在' + t.unit + '之' + midName(mid) + '前后。');
    } else {
      parts.push('本卦无变，格局不移，以「守」为要。');
    }

    return { key: q.unit, pos: mid + 1, text: parts.join('') };
  }

