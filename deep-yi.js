  /**
   * 合盘分维度事实（每一项都可独立核对，不合成总分）
   */
  function heDimensions(dayRel, zhiRel, comp, xiang) {
    var out = [];
    out.push({
      key: 'dayMaster', name: '日主关系', direction: 0,
      fact: dayRel.rel, text: dayRel.text
    });
    if (dayRel.rel === 'A生B' || dayRel.rel === 'B生A') {
      out[0].direction = 1;
      out[0].note = '一方生另一方，关系中有明确的给予方向。';
    } else if (dayRel.rel === '同气') {
      out[0].direction = 1;
      out[0].note = '日主相同，性情相投，但互补性弱。';
    } else if (dayRel.rel === 'A克B' || dayRel.rel === 'B克A') {
      out[0].direction = -1;
      out[0].note = '存在克制方向，关系中需注意力量均衡。';
    } else {
      out[0].note = '日主无明显生克偏向。';
    }

    var zdir = 0, znote = '日支无明显刑冲合害。';
    if (zhiRel) {
      if (zhiRel.name === '合') { zdir = 1; znote = '日支相合，传统视为关系基础稳固。'; }
      else if (zhiRel.name === '冲') { zdir = -1; znote = '日支相冲，传统视为张力大、磨合期长。'; }
      else if (zhiRel.name === '刑' || zhiRel.name === '害') { zdir = -1; znote = '日支相刑相害，传统视为易生磨擦。'; }
      else if (zhiRel.name === '破') { zdir = -1; znote = '日支相破，传统视为小有消磨。'; }
    }
    out.push({ key: 'dayZhi', name: '日支关系', direction: zdir, fact: zhiRel ? zhiRel.name : '无', note: znote });

    out.push({
      key: 'complement', name: '五行互补',
      direction: comp.length ? 1 : 0,
      fact: comp.length ? comp.length + ' 项存在明显差异' : '五行分布接近',
      note: comp.length
        ? '双方五行分布有 ' + comp.length + ' 项差异达 8 个百分点以上，可作为互补观察点。差异大小不等于关系好坏。'
        : '双方五行分布相近，互补性不明显，但相远方可比。'
    });

    out.push({
      key: 'shengXiao', name: '生肖关系',
      direction: xiang && xiang.rel === '三合' ? 1 : (xiang && xiang.rel === '相冲' ? -1 : 0),
      fact: xiang ? xiang.rel : '无',
      note: '生肖关系在传统合婚中权重较低，仅供参考。'
    });

    out.push({
      key: 'boundary', name: '结论边界', direction: 0,
      fact: '不可量化',
      note: '以上为出生年月日时干支与五行分布的事实对照，不含双方性格、交往史、家庭环境等因素，' +
        '不能预测关系走向，也不得作为婚配决策的唯一依据。'
    });
    return out;
  }

