  var GUA_TO_TRIGRAM = { '水': '坎', '火': '离', '山': '艮', '泽': '兑', '雷': '震', '风': '巽', '天': '乾', '地': '坤' };
  /** 全名 → [上卦, 下卦] */
  function shortOf(full) {
    if (full.length === 2) {
      var t0 = full[0];
      return GUA_TO_TRIGRAM[t0] ? [t0, t0] : null;
    }
    // 三字名「地天泰」/ 四字名「天火同人」，前两字均为上卦象、下卦象
    if (full.length === 3 || full.length === 4) {
      return [GUA_TO_TRIGRAM[full[0]], GUA_TO_TRIGRAM[full[1]]];
    }
    return null;
  }

